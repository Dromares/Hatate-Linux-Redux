#!/usr/bin/env python3
"""Writes Chromium's third-party credits page (chrome://credits) to a file.

    extract-credits.py CHROME_DIR OUT_HTML

Playwright's Chromium ships no separate credits file: the page lives,
brotli-compressed, in resources.pak. This reads the pak (format v5), finds
the resource that begins with the "Generated by licenses.py" marker, and
decompresses it with the `brotli` command-line tool. Exits non-zero if the
page cannot be found, so a Chromium that moved it fails the build instead
of shipping without its credits.
"""
import struct
import subprocess
import sys
from pathlib import Path

MARKER = b"<!-- Generated by licenses.py"
BROTLI_MAGIC = b"\x1e\x9b"        # then a 6-byte little-endian uncompressed size


def main() -> None:
    data = (Path(sys.argv[1]) / "resources.pak").read_bytes()
    version = struct.unpack_from("<I", data, 0)[0]
    if version != 5:
        sys.exit(f"extract-credits: resources.pak is format {version}, expected 5")
    count, _aliases = struct.unpack_from("<HH", data, 8)
    entries = [struct.unpack_from("<HI", data, 12 + 6 * i) for i in range(count + 1)]
    for i in range(count):
        blob = data[entries[i][1]:entries[i + 1][1]]
        if blob[:2] != BROTLI_MAGIC or len(blob) < 100_000:
            continue
        page = subprocess.run(["brotli", "-d", "-c"], input=blob[8:],
                              capture_output=True, check=False).stdout
        if page.startswith(MARKER):
            Path(sys.argv[2]).write_bytes(page)
            print(f"extract-credits: resource {entries[i][0]}, {len(page)} bytes")
            return
    sys.exit("extract-credits: the credits page was not found in resources.pak")


if __name__ == "__main__":
    main()
