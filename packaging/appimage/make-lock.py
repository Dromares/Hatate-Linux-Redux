#!/usr/bin/env python3
"""Regenerates requirements-appimage.txt: exact pins plus SHA-256 hashes.

    python3 packaging/appimage/make-lock.py > packaging/appimage/requirements-appimage.txt

The pins are the ones a resolve of requirements-lock.txt + Playwright
produced for CPython 3.13 on x86_64 Linux; edit PINS to change them. The
hashes come from PyPI's JSON API and cover every wheel that could be used
on this platform, so the build can run pip with --require-hashes
--only-binary=:all: and refuse anything PyPI did not publish under them.
"""
import json
import re
import sys
import urllib.request

PINS = {
    "PyQt6": "6.11.0", "PyQt6-Qt6": "6.11.2", "PyQt6-sip": "13.13.0",
    "requests": "2.34.2", "urllib3": "2.8.0", "idna": "3.20",
    "charset-normalizer": "3.5.2", "certifi": "2026.10.19",
    "beautifulsoup4": "4.15.0", "soupsieve": "3.0.3", "typing-extensions": "4.16.0",
    "lxml": "6.1.2", "Pillow": "12.3.0", "numpy": "2.5.2",
    "playwright": "1.64.0", "pyee": "14.0.0", "greenlet": "3.5.6",
}

USABLE = re.compile(r"(py3-none-any|cp313-cp313-(manylinux|musllinux)[^ ]*x86_64|"
                    r"cp313-abi3-manylinux[^ ]*x86_64|cp3\d+-abi3-manylinux[^ ]*x86_64|"
                    r"py3-none-manylinux[^ ]*x86_64|py2\.py3-none-any)")


def main() -> None:
    print("# Generated by make-lock.py - do not edit by hand.")
    print("# Exact pins of everything the AppImage installs, with the SHA-256 of every")
    print("# wheel usable on CPython 3.13 / x86_64 Linux (glibc).")
    for name, version in sorted(PINS.items(), key=lambda kv: kv[0].lower()):
        url = f"https://pypi.org/pypi/{name}/{version}/json"
        with urllib.request.urlopen(url) as resp:
            files = json.load(resp)["urls"]
        hashes = sorted({f["digests"]["sha256"] for f in files
                         if f["packagetype"] == "bdist_wheel"
                         and USABLE.search(f["filename"])
                         and "musllinux" not in f["filename"]})
        if not hashes:
            sys.exit(f"no usable wheel for {name}=={version}")
        print(f"{name}=={version} \\")
        print(" \\\n".join(f"    --hash=sha256:{h}" for h in hashes))
    # trailing newline from print


if __name__ == "__main__":
    main()
